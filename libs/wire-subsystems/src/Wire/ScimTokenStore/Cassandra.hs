-- | Add a new SCIM provisioning token. The token should be random and
-- generated by the backend, not by the user.
insertScimToken ::
  (HasCallStack, MonadClient m) =>
  ScimToken ->
  ScimTokenInfo ->
  m ()
insertScimToken token ScimTokenInfo {..} = retry x5 . batch $ do
  setType BatchLogged
  setConsistency LocalQuorum
  let tokenHash = hashScimToken token
  addPrepQuery insByToken (ScimTokenLookupKeyHashed tokenHash, stiTeam, stiId, stiCreatedAt, stiIdP, stiDescr, Just stiName)
  addPrepQuery insByTeam (ScimTokenLookupKeyHashed tokenHash, stiTeam, stiId, stiCreatedAt, stiIdP, stiDescr, Just stiName)

insByToken, insByTeam :: PrepQuery W ScimTokenRow ()
insByToken =
  [r|
    INSERT INTO team_provisioning_by_token
      (token_, team, id, created_at, idp, descr, name)
      VALUES (?, ?, ?, ?, ?, ?, ?)
  |]
insByTeam =
  [r|
    INSERT INTO team_provisioning_by_team
      (token_, team, id, created_at, idp, descr, name)
      VALUES (?, ?, ?, ?, ?, ?, ?)
  |]

scimTokenLookupKey :: ScimTokenRow -> ScimTokenLookupKey
scimTokenLookupKey (key, _, _, _, _, _, _) = key

-- | Check whether a token exists and if yes, what team and IdP are
-- associated with it. Plaintext-key rows are converted to hashed-key rows as a
-- side effect (legacy tokens are re-keyed on first use).
lookupScimToken ::
  (HasCallStack, MonadClient m) =>
  ScimToken ->
  m (Maybe ScimTokenInfo)
lookupScimToken token = do
  mRow <- lookupScimTokenRaw token
  case mRow of
    Just (ScimTokenLookupKeyPlaintext plain, info) -> do
      convertPlaintextToken plain info
      pure (Just info)
    Just (ScimTokenLookupKeyHashed _, info) -> pure (Just info)
    Nothing -> pure Nothing

-- | Read the token row under both its hashed and plaintext key, returning the
-- key it was found under together with the row info. Does not re-key.
lookupScimTokenRaw ::
  (HasCallStack, MonadClient m) =>
  ScimToken ->
  m (Maybe (ScimTokenLookupKey, ScimTokenInfo))
lookupScimTokenRaw token = do
  let tokenHash = hashScimToken token
  rows <- retry x1 . query sel $ params LocalQuorum (tokenHash, token)
  pure $ case fmap (scimTokenLookupKey &&& fromScimTokenRow) rows of
    [(key, info)] -> Just (key, info)
    -- Both keys present (partially converted row): prefer the plaintext row so
    -- the conversion below re-runs and removes the stale plaintext row.
    [(ScimTokenLookupKeyPlaintext plain, info), (ScimTokenLookupKeyHashed _, _)] -> Just (ScimTokenLookupKeyPlaintext plain, info)
    [(ScimTokenLookupKeyHashed _, _), (ScimTokenLookupKeyPlaintext plain, info)] -> Just (ScimTokenLookupKeyPlaintext plain, info)
    _ -> Nothing
  where
    sel :: PrepQuery R (ScimTokenHash, ScimToken) ScimTokenRow
    sel =
      [r|
      SELECT token_, team, id, created_at, idp, descr, name
        FROM team_provisioning_by_token WHERE token_ in (?, ?)
      |]

convertPlaintextToken ::
  (HasCallStack, MonadClient m) =>
  ScimToken ->
  ScimTokenInfo ->
  m ()
convertPlaintextToken token ScimTokenInfo {..} = retry x5 . batch $ do
  setType BatchLogged
  setConsistency LocalQuorum
  let tokenHash = hashScimToken token
  -- enter by new lookup key
  addPrepQuery insByToken (ScimTokenLookupKeyHashed tokenHash, stiTeam, stiId, stiCreatedAt, stiIdP, stiDescr, Just stiName)
  -- update info table
  addPrepQuery insByTeam (ScimTokenLookupKeyHashed tokenHash, stiTeam, stiId, stiCreatedAt, stiIdP, stiDescr, Just stiName)
  -- remove old lookup key
  addPrepQuery delByTokenLookup (Identity (ScimTokenLookupKeyPlaintext token))

-- | List all tokens associated with a team, in the order of their creation.
getScimTokens ::
  (HasCallStack, MonadClient m) =>
  TeamId ->
  m [ScimTokenInfo]
getScimTokens team = do
  -- We don't need pagination here because the limit should be pretty low
  -- (e.g. 16). If the limit grows, we might have to introduce pagination.
  rows <- retry x1 . query sel $ params LocalQuorum (Identity team)
  pure $ sortOn (.stiCreatedAt) $ map fromScimTokenRow rows
  where
    sel :: PrepQuery R (Identity TeamId) ScimTokenRow
    sel =
      [r|
      SELECT token_, team, id, created_at, idp, descr, name
        FROM team_provisioning_by_team WHERE team = ?
      |]

-- | Delete a token.
deleteScimToken ::
  (HasCallStack, MonadClient m) =>
  TeamId ->
  ScimTokenId ->
  m ()
deleteScimToken team tokenid = do
  mbToken <- retry x1 . query1 selById $ params LocalQuorum (team, tokenid)
  retry x5 . batch $ do
    setType BatchLogged
    setConsistency LocalQuorum
    addPrepQuery delById (team, tokenid)
    for_ mbToken $ \(Identity key) ->
      addPrepQuery delByTokenLookup (Identity key)

selById :: PrepQuery R (TeamId, ScimTokenId) (Identity ScimTokenLookupKey)
selById =
  [r|
  SELECT token_ FROM team_provisioning_by_team
    WHERE team = ? AND id = ?
|]

delById :: PrepQuery W (TeamId, ScimTokenId) ()
delById =
  [r|
  DELETE FROM team_provisioning_by_team
    WHERE team = ? AND id = ?
  |]

delByTokenLookup :: PrepQuery W (Identity ScimTokenLookupKey) ()
delByTokenLookup =
  [r|
  DELETE FROM team_provisioning_by_token
    WHERE token_ = ?
|]

-- | Delete all tokens belonging to a team.
deleteTeamScimTokens ::
  (HasCallStack, MonadClient m) =>
  TeamId ->
  m ()
deleteTeamScimTokens team = do
  tokens <- retry x5 $ query sel $ params LocalQuorum (Identity team)
  retry x5 . batch $ do
    setType BatchLogged
    setConsistency LocalQuorum
    addPrepQuery delByTeam (Identity team)
    mapM_ (addPrepQuery delByTokenLookup) tokens
  where
    sel :: PrepQuery R (Identity TeamId) (Identity ScimTokenLookupKey)
    sel = "SELECT token_ FROM team_provisioning_by_team WHERE team = ?"
    delByTeam :: PrepQuery W (Identity TeamId) ()
    delByTeam = "DELETE FROM team_provisioning_by_team WHERE team = ?"

updateScimTokenName :: (HasCallStack, MonadClient m) => TeamId -> ScimTokenId -> Text -> m ()
updateScimTokenName team tokenid name = do
  mbToken <- retry x1 . query1 selById $ params LocalQuorum (team, tokenid)
  retry x5 . batch $ do
    setType BatchLogged
    setConsistency LocalQuorum
    addPrepQuery updateNameById (name, team, tokenid)
    for_ mbToken $ \(Identity key) ->
      addPrepQuery updateNameByTokenLookup (name, key)
  where
    updateNameById :: PrepQuery W (Text, TeamId, ScimTokenId) ()
    updateNameById =
      [r|
        UPDATE team_provisioning_by_team
          SET name = ?
          WHERE team = ? AND id = ?
      |]

    updateNameByTokenLookup :: PrepQuery W (Text, ScimTokenLookupKey) ()
    updateNameByTokenLookup =
      [r|
        UPDATE team_provisioning_by_token
          SET name = ?
          WHERE token_ = ?
      |]

type ScimTokenRow = (ScimTokenLookupKey, TeamId, ScimTokenId, UTCTime, Maybe SAML.IdPId, Text, Maybe Text)

fromScimTokenRow :: ScimTokenRow -> ScimTokenInfo
fromScimTokenRow (_, stiTeam, stiId, stiCreatedAt, stiIdP, stiDescr, stiName) =
  ScimTokenInfo
    { stiId,
      stiTeam,
      stiCreatedAt,
      stiIdP,
      stiDescr,
      stiName = fromMaybe (idToText stiId) stiName
    }
